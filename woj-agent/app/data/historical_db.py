def get_era_baseline(season_end_year: int) -> Dict[str, float]:
    """Retrieve league baseline stats for a season. Interpolates if missing."""
    if season_end_year in ERA_BASELINES:
        return ERA_BASELINES[season_end_year]
    # Find closest season
    closest_year = min(ERA_BASELINES.keys(), key=lambda y: abs(y - season_end_year))
    return ERA_BASELINES[closest_year]


def calculate_relative_ts(player_ts: float, season_end_year: int) -> float:
    """Calculate Relative True Shooting Percentage: Player TS% - League Average TS%.
    Example: 0.640 - 0.535 = +10.5% (+0.105)
    """
    baseline = get_era_baseline(season_end_year)
    return round((player_ts - baseline["lg_ts"]) * 100, 2)


